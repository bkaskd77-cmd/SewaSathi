/*
 * Web push subscriptions — one row per browser a person has opted in on.
 *
 * WHY A TABLE AND NOT A COLUMN. One person has several browsers, and a push
 * subscription belongs to a browser rather than to an account: a professional
 * with the app on their phone and the dashboard open on a laptop has two, and
 * either may be revoked by the browser without the other knowing. A column
 * would silently mean "the last device that said yes", so the person who
 * opted in on their phone would stop being reached the day they opened the
 * laptop.
 *
 * `payout.destinationChanged` IS THE REASON THAT MATTERS. That notification
 * exists to reach somebody who did NOT make the change — an account takeover's
 * first move is to redirect the money — and `lib/notify/channel.ts` already
 * records the trap: an SMS channel reading the number at send time would warn
 * the attacker about their own theft. A push subscription cannot be redirected
 * from inside the product at all; it is held by the browser and the push
 * service. Keeping every one of a person's devices is what makes the warning
 * land on the handset in their pocket.
 *
 * THE KEYS ARE NOT A SECRET OF OURS AND ARE NOT TREATED AS ONE. `p256dh` and
 * `auth` are generated by the recipient's own browser and are what let us
 * encrypt to it; they are useless without the endpoint and grant nothing but
 * the ability to send that browser a notification. They are still personal
 * data — an endpoint identifies a device — so the table is admin-read only and
 * no browser may read anybody's rows, including its own. There is nothing on a
 * screen for a person to read here: the browser already knows its own
 * subscription, and asking the server would be asking a question it answered
 * itself.
 */

create table if not exists public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.profiles(id) on delete cascade,

  /*
   * The push service's URL for this browser. UNIQUE, because the same browser
   * re-subscribing must overwrite its row rather than add a second one — a
   * duplicate means every notification is sent twice to one phone.
   */
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,

  /*
   * The language this browser asked in, so a push can be rendered without
   * reading the profile.
   *
   * NULL IS "NOT RECORDED", NEVER A DEFAULT LANGUAGE — rule 6. A null here
   * falls back to `profiles.preferred_language`, which is the answer the person
   * actually gave; writing 'en' for a row we never asked would quietly make
   * English the answer for everybody who subscribed before this column meant
   * anything.
   */
  locale text check (locale in ('en', 'ne')),

  created_at timestamptz not null default now(),

  /*
   * When the push service last refused this endpoint for good (404/410).
   *
   * KEPT RATHER THAN DELETED ON THE SPOT, for one phase at least: a sweep that
   * deletes on the first refusal cannot tell "this browser is gone" from "the
   * push service had a bad minute", and a deleted row is a person who silently
   * stops being notified. Null is "never refused".
   */
  gone_at timestamptz,

  /** Last time a send to this endpoint was accepted. Null is "never yet". */
  last_sent_at timestamptz
);

alter table public.push_subscriptions enable row level security;

/*
 * NO BROWSER WRITES THIS TABLE AT ALL, which is deliberate and is the opposite
 * of the obvious design. A subscription arrives from the browser, so the
 * tempting shape is an insert policy for `authenticated` — and that is a row
 * whose `profile_id` the browser chooses. Subscribing somebody else's account
 * to your own endpoint would deliver their booking progress, their arrival
 * notices and their payout-destination warning to your phone. So the write
 * goes through a server action under the service role, which re-reads the
 * session and names the actor itself: `lib/data/push.ts`, the rule this
 * repository already follows for `payments`.
 */
revoke all on public.push_subscriptions from anon, authenticated;

create index if not exists push_subscriptions_profile_idx
  on public.push_subscriptions (profile_id)
  where gone_at is null;

create policy "Admins read every push subscription"
  on public.push_subscriptions for select
  to authenticated
  using (public.is_admin());

/*
 * SELECT for the admin policy above and nothing else. A new table grants
 * nothing by default since 20261002000001, so a policy with no grant answers
 * `permission denied` — the trap that migration's own note records.
 */
grant select on public.push_subscriptions to authenticated;

comment on table public.push_subscriptions is
  'One row per browser opted in to web push. Written only by the service role; see lib/data/push.ts.';

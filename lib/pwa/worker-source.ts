import { CACHE_RULE, PRECACHE_PATHS, cachePolicy } from "./cache-rule";

/**
 * The service worker, generated rather than written.
 *
 * IT LIVES IN `lib/` RATHER THAN BESIDE THE ROUTE because a Next route file
 * may export nothing but its handlers and a few known config names — an extra
 * export fails the build's type check, which is how this landed here. The
 * placement is better anyway: the generator is the other half of
 * `cache-rule.ts` and the test reaches it without going through a route.
 *
 * WHY GENERATED AND NOT A FILE IN `public/`. Two reasons, and both are the difference
 * between a worker that can be reasoned about and one that has to be trusted.
 *
 *   The decision about what may be cached is `cachePolicy`, and its own source
 *   text is pasted into the script below. The worker and
 *   `tests/unit/pwa-cache-rule.test.ts` therefore execute the same characters:
 *   a rule reimplemented inside the worker would be the one-list-written-twice
 *   sin with money attached, and it would fail in the quietest possible way,
 *   because a worker serving a stale price looks exactly like a working
 *   application. The test asserts the paste, so the two cannot drift.
 *
 *   The cache name carries `BUILD_COMMIT`. A deploy therefore changes the cache
 *   name, `activate` deletes every cache that is not the current one, and
 *   nobody is left running last week's assets. A file in `public/` could not
 *   see the commit.
 *
 * `Cache-Control: no-store` IS LOAD-BEARING AND IS THE CLASSIC WAY TO GET STUCK.
 * Browsers cap a worker script's own freshness at 24 hours, but an intermediary
 * that caches it for a day is a day in which no update can reach anybody — and
 * the whole point of the version above is that an update always can. The
 * browser re-fetches this URL on every navigation and compares bytes; `no-store`
 * is what makes that comparison mean anything.
 *
 * `Service-Worker-Allowed: /` lets a script served from `/sw.js` claim the whole
 * origin. It is served from the root already, so this is belt and braces rather
 * than a widening — and it is the header to remember if the path ever moves.
 */

/**
 * The name the pasted rule is bound to inside the worker.
 *
 * THE FUNCTION'S OWN NAME IS NOT USABLE, AND THIS SHIPPED WRONG INTO A
 * PRODUCTION BUILD BEFORE IT WAS CAUGHT. `CacheRule` was already parameterised
 * so the rule would close over nothing a minifier could rename — and the thing
 * the minifier renamed was the FUNCTION ITSELF. `next build` turned
 * `cachePolicy` into `function f(a,b){...}`, so the generated script defined
 * `f` and called `cachePolicy`, which is a `ReferenceError` on the worker's
 * first fetch. The browser then discards the worker and every page keeps
 * working, with no offline shell, nothing in any log this product reads, and
 * a green test suite — because vitest does not minify.
 *
 * Binding the paste to a name WE choose removes the dependency on the compiler
 * entirely: a named function expression keeps working whatever its own name is
 * reduced to, including none. Found by reading the bytes `next start` actually
 * served rather than by any check, which is why `tests/unit/pwa-cache-rule.test.ts`
 * now runs the generated script with a deliberately renamed rule.
 */
const CACHE_DECIDER = "decideCache";

/**
 * The worker's source, with the shared rule pasted in.
 *
 * `ruleSource` IS A PARAMETER SO THE TEST CAN HAND IT A RENAMED FUNCTION, and
 * that exists because the first version of this file shipped broken into a
 * production build. See `CACHE_DECIDER` below.
 */
export function serviceWorkerSource(
  commit: string,
  ruleSource: string = cachePolicy.toString(),
): string {
  return `/*
 * SajiloKaam service worker. Generated by app/sw.js/route.ts — do not edit a
 * copy of this; edit lib/pwa/cache-rule.ts and the generator.
 *
 * Build: ${commit}
 */
"use strict";

const VERSION = ${JSON.stringify(commit)};
const CACHE = "sajilokaam-" + VERSION;
const PRECACHE_PATHS = ${JSON.stringify(PRECACHE_PATHS)};
const CACHE_RULE = ${JSON.stringify(CACHE_RULE)};

/* ---- the shared rule, pasted from lib/pwa/cache-rule.ts ---- */
const ${CACHE_DECIDER} = ${ruleSource};
/* ---- end of the shared rule ---- */

/**
 * Store the shell. A precache that cannot be completed must not install a
 * worker that then has no offline page to serve, so this is all-or-nothing.
 */
self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE_PATHS))
      .then(() => self.skipWaiting()),
  );
});

/**
 * Take over immediately and delete every other version.
 *
 * skipWaiting + claim is what makes a deploy land rather than wait for every
 * tab to close. The risk it carries here is bounded by the rule above: the only
 * thing this worker holds for a long time is content-hashed output, so a page
 * that asks for a chunk the new cache does not have gets a cache MISS and falls
 * through to the network. A miss is a slow load; a wrong file would be a bug,
 * and hashed URLs make that impossible.
 */
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) =>
        Promise.all(
          names
            .filter((name) => name !== CACHE)
            .map((name) => caches.delete(name)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

/** Which offline page to answer with, by the language of the request. */
function offlinePathFor(url) {
  return url.pathname === "/ne" || url.pathname.startsWith("/ne/")
    ? "/ne/offline"
    : "/offline";
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);

  const verdict = ${CACHE_DECIDER}(
    {
      method: request.method,
      sameOrigin: url.origin === self.location.origin,
      pathname: url.pathname,
      navigation: request.mode === "navigate",
    },
    CACHE_RULE,
  );

  /*
   * A DOCUMENT IS FETCHED AND NEVER STORED. On failure the precached offline
   * page is served, which is a different page rather than a stale version of
   * the one that was asked for — the distinction the whole worker turns on.
   */
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() =>
        caches
          .match(offlinePathFor(url))
          .then(
            (cached) =>
              cached ||
              new Response("", { status: 503, statusText: "Offline" }),
          ),
      ),
    );
    return;
  }

  /*
   * Everything else the rule refuses is left entirely alone — no respondWith at
   * all, so the browser does what it would have done with no worker installed.
   * That is deliberately not "fetch and pass it through": a worker in the path
   * of every API call is a worker that can break one, and it buys nothing here.
   */
  if (verdict === "never") return;

  if (verdict === "immutable") {
    event.respondWith(
      caches.match(request).then((cached) => {
        if (cached) return cached;
        return fetch(request).then((response) => {
          /*
           * Only a complete, same-origin 200 is stored. An opaque or partial
           * response cached under a hashed URL would be unrecoverable — the URL
           * never changes again, so the bad copy would be permanent.
           */
          if (response.ok && response.status === 200 && response.type === "basic") {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        });
      }),
    );
    return;
  }

  // precache: the shell, the manifest and the icons. Cache-first, then network.
  event.respondWith(
    caches
      .match(request)
      .then((cached) => cached || fetch(request)),
  );
});
`;
}
